package dev.ronaldnguyen.portfolio.seed;

import dev.ronaldnguyen.portfolio.rag.ChunkDraft;
import jakarta.json.JsonArray;
import jakarta.json.JsonObject;
import jakarta.json.JsonString;
import jakarta.json.JsonValue;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;

/**
 * Turns the structured CV into self-contained prose chunks: one per job,
 * degree, thesis, skill category, plus about / availability / languages /
 * contact. Each chunk starts with a sentence that names its context, so an
 * extracted sentence still makes sense on its own.
 */
public final class ProfileChunker {

    public static final String SOURCE_TYPE = "cv";

    private ProfileChunker() {
    }

    public static List<ChunkDraft> chunks(JsonObject p) {
        List<ChunkDraft> drafts = new ArrayList<>();
        String name = p.getString("name");
        String linkedin = p.getString("linkedin");

        drafts.add(cv("cv:about", "About", "About " + name, linkedin,
                name + " is a " + p.getString("headline") + " based in " + p.getString("location") + ". "
                        + p.getString("about")));

        drafts.add(cv("cv:availability", "Availability", "Availability & Master's thesis", null,
                p.getString("availability") + " Interested companies can contact him by email at "
                        + p.getString("email") + "."));

        drafts.add(cv("cv:contact", "Contact", "Contact & Links", p.getString("github"),
                "You can contact Ronald by email at " + p.getString("email") + ". "
                        + "His GitHub profile is " + p.getString("github") + ". "
                        + "His LinkedIn profile is " + linkedin + ". "
                        + "He is based in " + p.getString("location") + "."));

        for (JsonValue value : p.getJsonArray("experience")) {
            JsonObject job = value.asJsonObject();
            boolean current = job.getBoolean("current", false);
            StringBuilder text = new StringBuilder();
            text.append(current ? "Ronald currently works as " : "Ronald worked as ")
                    .append(job.getString("role")).append(" at ").append(job.getString("company"))
                    .append(" in ").append(job.getString("location"))
                    .append(" (").append(job.getString("period")).append(").");
            for (String bullet : strings(job.getJsonArray("bullets"))) {
                text.append(' ').append(bullet);
            }
            List<String> tools = strings(job.getJsonArray("tools"));
            if (!tools.isEmpty()) {
                text.append(" Technologies and tools used in this role: ")
                        .append(String.join(", ", tools)).append('.');
            }
            drafts.add(cv("cv:experience:" + job.getString("id"), "Experience",
                    job.getString("role") + " — " + job.getString("company"), null, text.toString()));
        }

        for (JsonValue value : p.getJsonArray("education")) {
            JsonObject edu = value.asJsonObject();
            String degree = edu.getString("degree");
            String period = edu.getString("period");
            boolean ongoing = period.toLowerCase(Locale.ROOT).contains("expected");
            String verb = ongoing ? "Ronald is currently studying for the "
                    : degree.startsWith("Abitur") ? "Ronald obtained his " : "Ronald completed the ";
            String text = verb + degree + " at " + edu.getString("institution") + ", "
                    + edu.getString("location") + " (" + period + "). " + edu.getString("grade") + ".";
            drafts.add(cv("cv:education:" + edu.getString("id"), "Education",
                    degree + " — " + edu.getString("institution"), null, text));

            JsonObject thesis = edu.getJsonObject("thesis");
            if (thesis != null) {
                drafts.add(cv("cv:thesis:" + edu.getString("id"), "Education", "Bachelor's Thesis", null,
                        "Ronald's Bachelor's thesis is titled \"" + thesis.getString("title") + "\" "
                                + "(German original: \"" + thesis.getString("titleOriginal") + "\"). "
                                + "The thesis was graded " + thesis.getString("grade")
                                + " and was written as part of his " + degree + " at "
                                + edu.getString("institution") + ". "
                                + "It is an empirical evaluation of code transformations generated by "
                                + "large language models (LLMs) in real-world software systems of varying complexity."));
            }
        }

        for (JsonValue value : p.getJsonArray("skills")) {
            JsonObject group = value.asJsonObject();
            String category = group.getString("category");
            drafts.add(cv("cv:skills:" + slug(category), "Skills", category, null,
                    "Ronald's skills in the area " + category + ": "
                            + String.join(", ", strings(group.getJsonArray("items"))) + "."));
        }

        List<String> languages = new ArrayList<>();
        for (JsonValue value : p.getJsonArray("languages")) {
            JsonObject lang = value.asJsonObject();
            languages.add(lang.getString("language") + " (" + lang.getString("level") + ")");
        }
        drafts.add(cv("cv:languages", "Skills", "Spoken Languages",
                null, "Ronald speaks " + String.join(" and ", languages) + "."));

        return drafts;
    }

    private static ChunkDraft cv(String key, String section, String title, String url, String content) {
        return new ChunkDraft(SOURCE_TYPE, key, section, title, url, 0, content);
    }

    private static List<String> strings(JsonArray array) {
        if (array == null) {
            return List.of();
        }
        return array.getValuesAs(JsonString.class).stream().map(JsonString::getString).toList();
    }

    static String slug(String value) {
        return value.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9]+", "-").replaceAll("(^-|-$)", "");
    }
}
